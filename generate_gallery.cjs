/**
 * Regenerates data/gallery.js from whatever is in public/gallery.
 * Run with `npm run gallery` after adding or removing photos.
 *
 * Alt text is NOT baked in here — it's rendered from the `gallery.alt`
 * message key so it follows the visitor's language.
 */
const fs = require('fs');
const path = require('path');

const publicGalleryDir = path.join(__dirname, 'public', 'gallery');
const outputFilePath = path.join(__dirname, 'data', 'gallery.js');

try {
  const files = fs.readdirSync(publicGalleryDir);
  const imageFiles = files.filter((file) =>
    /\.(jpg|jpeg|png|gif|webp|avif)$/i.test(file)
  );

  // Sort naturally so sunrise-2 comes before sunrise-10
  imageFiles.sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  const galleryItems = imageFiles.map(
    (file, index) => `  { id: ${index + 1}, url: '/gallery/${file}' },`
  );

  const fileContent = `// Automatically generated by generate_gallery.cjs — do not edit by hand.
// Run \`npm run gallery\` to refresh after changing public/gallery.
export const galleryImages = [
${galleryItems.join('\n')}
];
`;

  fs.writeFileSync(outputFilePath, fileContent, 'utf-8');
  console.log(
    `Successfully wrote ${imageFiles.length} items to ${outputFilePath}`
  );
} catch (error) {
  console.error('Error generating gallery:', error);
  process.exitCode = 1;
}
